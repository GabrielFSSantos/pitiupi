package pitiupi.chat.GUI;

import java.text.SimpleDateFormat;
import java.util.Date;
import pitiupi.chat.net.ChatMessage;
import pitiupi.control.ConnectionManager;
import pitiupi.models.Messages.Message;

import javax.swing.*;

/**
 *
 * @author flavio
 */
public class ChatWindow extends JDialog {

    private JButton jButton1;
    private JEditorPane jEditorPane1;
    private JPanel jPanel1;
    private JPanel jPanel2;
    private JScrollPane jScrollPane1;
    private JScrollPane jScrollPane2;
    private JSplitPane jSplitPane1;
    private JTextArea jTextArea1;

    private final ConnectionManager connectionManager;

    public ChatWindow(ConnectionManager connectionManager) {
        this.connectionManager = connectionManager;
        initComponents();
    }

    /**
     * This method is called from within the constructor to initialize the form.
     * WARNING: Do NOT modify this code. The content of this method is always
     * regenerated by the Form Editor.
     */
    private void initComponents() {

        this.setDefaultCloseOperation(WindowConstants.HIDE_ON_CLOSE);
        this.setTitle("Chat Window");
        this.setBounds(new java.awt.Rectangle(0, 0, 800, 600));
        this.getContentPane().setLayout(new java.awt.BorderLayout(5, 5));
        this.setPreferredSize(new java.awt.Dimension(800, 600));

        jSplitPane1 = new JSplitPane();
        jScrollPane1 = new JScrollPane();
        jEditorPane1 = new JEditorPane();
        jPanel1 = new JPanel();
        jScrollPane2 = new JScrollPane();
        jTextArea1 = new JTextArea();
        jPanel2 = new JPanel();
        jButton1 = new JButton();

        jSplitPane1.setDividerLocation(500);
        jSplitPane1.setOrientation(JSplitPane.VERTICAL_SPLIT);
        jEditorPane1.setContentType("text/html");
        jPanel1.setLayout(new java.awt.BorderLayout());
        jTextArea1.setColumns(20);
        jTextArea1.setRows(5);
        jTextArea1.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                if (evt.getKeyChar() == '\n') {
                    sendMessage();
                }
            }
        });
        jButton1.setText("Send");

        jScrollPane1.setViewportView(jEditorPane1);
        jScrollPane2.setViewportView(jTextArea1);
        jSplitPane1.setTopComponent(jScrollPane1);

        jPanel1.add(jScrollPane2, java.awt.BorderLayout.CENTER);
        jPanel2.setLayout(new java.awt.FlowLayout(java.awt.FlowLayout.RIGHT));
        jButton1.addActionListener((java.awt.event.ActionEvent evt) -> {
            sendMessage();
        });
        jPanel2.add(jButton1);
        jPanel1.add(jPanel2, java.awt.BorderLayout.PAGE_END);
        jSplitPane1.setRightComponent(jPanel1);
        getContentPane().add(jSplitPane1, java.awt.BorderLayout.CENTER);
        pack();
    }

    private void sendMessage() {
        if (jTextArea1.getText().trim().isEmpty()) {
            return;
        }
        ChatMessage message = new ChatMessage(connectionManager.getUserName(), jTextArea1.getText());
        this.sendChatMessage(message);
        jTextArea1.setText("");
    }

    public void sendChatMessage(Message message) {
        connectionManager.sendUdpMulticast(message);
    }

    public void receiveChatMessage(ChatMessage message) {
        SimpleDateFormat dt = new SimpleDateFormat("dd/MM/yyyyy hh:mm:ss");
        Date date = new Date();
        this.receiveChatMessage(dt.format(date) + " "
                + "<b>" + message.getName() + "</b>: "
                + message.getText() + "<br>");
    }

    public void receiveChatMessage(String message) {
        jEditorPane1.setText(message + jEditorPane1.getText());
    }
}
